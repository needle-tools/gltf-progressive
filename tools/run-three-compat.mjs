#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";
import path from "node:path";
import process from "node:process";

const repoRoot = process.cwd();
const statusPath = path.join(repoRoot, "tests/compat/THREE-COMPAT-STATUS.md");
const jsonPath = path.join(repoRoot, ".cache/gltf-progressive-three-compat-status.json");

if (process.argv[2] === "--from-artifact") {
    const artifactPath = process.argv[3] ? path.resolve(repoRoot, process.argv[3]) : jsonPath;
    const artifact = JSON.parse(await readFile(artifactPath, "utf8"));
    await writeFile(statusPath, renderMarkdown(artifact), "utf8");
    process.exit(0);
}

const extraCacheArgs = process.argv.slice(2);
const buildResult = await runCommand("npm", ["run", "build:lib"], { env: process.env });
process.stdout.write(buildResult.output);
process.stderr.write(buildResult.errorOutput);
if (buildResult.exitCode !== 0) process.exit(buildResult.exitCode);

const cacheResult = await runCommand("npm", ["run", "compat:cache", "--", ...extraCacheArgs], { env: process.env });
process.stdout.write(cacheResult.output);
process.stderr.write(cacheResult.errorOutput);
if (cacheResult.exitCode !== 0) process.exit(cacheResult.exitCode);

const testResult = await runCommand("npm", ["run", "test:compat:browser", "--", "--reporter=verbose", "tests/compat/gltf-progressive-three-compat.browser.test.ts"], {
    env: process.env,
});
process.stdout.write(testResult.output);
process.stderr.write(testResult.errorOutput);

const artifact = extractArtifact(testResult.output + "\n" + testResult.errorOutput);
if (artifact) {
    await mkdir(path.dirname(jsonPath), { recursive: true });
    await writeFile(jsonPath, JSON.stringify(artifact, null, 2) + "\n", "utf8");
    await writeFile(statusPath, renderMarkdown(artifact), "utf8");
}

process.exit(testResult.exitCode);

async function runCommand(command, args, options) {
    return await new Promise(resolve => {
        const child = spawn(command, args, {
            cwd: repoRoot,
            env: options.env,
            stdio: ["ignore", "pipe", "pipe"],
        });

        let output = "";
        let errorOutput = "";
        child.stdout.on("data", chunk => {
            output += chunk.toString();
        });
        child.stderr.on("data", chunk => {
            errorOutput += chunk.toString();
        });
        child.on("close", exitCode => {
            resolve({
                exitCode: exitCode ?? 1,
                output,
                errorOutput,
            });
        });
    });
}

function extractArtifact(output) {
    const prefix = "[gltf-progressive-three-compat-artifact] ";
    const line = [...output.split(/\r?\n/)].reverse().find(entry => entry.startsWith(prefix));
    if (!line) return null;
    return JSON.parse(line.slice(prefix.length));
}

function renderMarkdown(artifact) {
    const lines = [];
    lines.push("# glTF Progressive Three Compat Status");
    lines.push("");
    lines.push("_Generated by `npm run test:compat:three`._");
    lines.push("");
    lines.push(`Generated: \`${artifact.generatedAt}\``);
    lines.push("");
    lines.push("Summary:");
    lines.push(`- passed: \`${artifact.summary.passed}\``);
    lines.push(`- renderer unsupported: \`${artifact.summary.unsupported}\``);
    lines.push(`- fixture unsupported: \`${countUnsupportedWorkerFixtures(artifact.results)}\``);
    lines.push(`- failed: \`${artifact.summary.failed}\``);
    lines.push(`- total: \`${artifact.totalCases}\``);
    lines.push("");
    lines.push("## Renderer Matrix");
    lines.push("");
    lines.push("| Version | WebGL | WebGPU forceWebGL2 | WebGPU native |");
    lines.push("| --- | --- | --- | --- |");

    for (const [version, results] of groupByVersion(artifact.results)) {
        const cells = ["webgl", "webgpu-force-webgl2", "webgpu"].map(mode => {
            const result = results.find(entry => entry.rendererMode === mode);
            const failure = artifact.failures.find(entry => entry.startsWith(`${version}:${mode}:`));
            if (result?.status === "ready") return "ok";
            if (result?.status === "unsupported") return "n/a";
            if (failure) return "fail";
            return "-";
        });
        lines.push(`| \`${version}\` | ${cells.join(" | ")} |`);
    }
    lines.push("");

    const firstReadyResult = artifact.results.find(result => result.status === "ready" && result.suite);
    if (firstReadyResult?.suite?.fixtureAssets?.length) {
        lines.push("## Cached Fixture Assets");
        lines.push("");
        lines.push("| Fixture | Bytes | Referenced GLBs | Page load coverage | Worker load coverage |");
        lines.push("| --- | ---: | ---: | --- | --- |");
        for (const asset of firstReadyResult.suite.fixtureAssets) {
            lines.push([
                `\`${asset.id}\``,
                String(asset.bytes),
                String(asset.dependencyCount),
                summarizePageFixtureCoverage(artifact.results, asset.id),
                summarizeWorkerFixtureCoverage(artifact.results, asset.id),
            ].join(" | ").replace(/^/, "| ").replace(/$/, " |"));
        }
        lines.push("");
    }

    lines.push("## Fixture Matrix");
    lines.push("");
    lines.push("| Version | Mode | Page fixtures | Worker product | Worker world | Notes |");
    lines.push("| --- | --- | --- | --- | --- | --- |");
    for (const result of artifact.results) {
        lines.push([
            `\`${result.version}\``,
            `\`${result.rendererMode}\``,
            getPageFixtureCell(result),
            getWorkerFixtureCell(result, "forgotten-knight-product"),
            getWorkerFixtureCell(result, "forgotten-knight-world"),
            getFixtureNotes(result),
        ].join(" | ").replace(/^/, "| ").replace(/$/, " |"));
    }
    lines.push("");

    const unsupportedWorkerFixtures = collectUnsupportedWorkerFixtures(artifact.results);
    if (unsupportedWorkerFixtures.length) {
        lines.push("## Known Unsupported Fixture Paths");
        lines.push("");
        for (const entry of unsupportedWorkerFixtures) {
            lines.push(`- \`${entry.assetId}\` in Worker: ${entry.count} case(s). ${entry.reason}`);
        }
        lines.push("");
    }

    if (artifact.failures.length) {
        lines.push("## Failure Details");
        lines.push("");
        for (const failure of artifact.failures) {
            lines.push(`- ${failure.replace(/\n+/g, "\n  ")}`);
        }
        lines.push("");
    }

    lines.push("## Raw Artifact");
    lines.push("");
    lines.push(`- JSON: \`.cache/gltf-progressive-three-compat-status.json\``);
    lines.push("");
    return lines.join("\n");
}

function summarizePageFixtureCoverage(results, assetId) {
    const readyResults = results.filter(result => result.status === "ready" && result.suite);
    const loaded = readyResults.filter(result => {
        const asset = result.suite.fixtureAssets.find(entry => entry.id === assetId);
        return asset?.sceneChildren > 0;
    }).length;
    return readyResults.length ? `${loaded}/${readyResults.length} ok` : "-";
}

function summarizeWorkerFixtureCoverage(results, assetId) {
    const readyResults = results.filter(result => result.status === "ready" && result.suite);
    const statuses = new Map();
    for (const result of readyResults) {
        const asset = result.suite.worker.assets?.find(entry => entry.id === assetId);
        const status = asset?.status || "not run";
        statuses.set(status, (statuses.get(status) || 0) + 1);
    }
    if (!statuses.size) return "-";
    return [...statuses.entries()].map(([status, count]) => `${count} ${status}`).join(", ");
}

function getPageFixtureCell(result) {
    if (result.status !== "ready" || !result.suite) return "renderer n/a";
    const loaded = result.suite.fixtureAssets.filter(asset => asset.sceneChildren > 0).length;
    return `${loaded}/${result.suite.fixtureAssets.length} ok`;
}

function getWorkerFixtureCell(result, assetId) {
    if (result.status !== "ready" || !result.suite) return "renderer n/a";
    const asset = result.suite.worker.assets?.find(entry => entry.id === assetId);
    if (!asset) return "not run";
    if (asset.status === "loaded") return "ok";
    if (asset.status === "unsupported") return "n/a";
    return "fail";
}

function getFixtureNotes(result) {
    if (result.status !== "ready" || !result.suite) return escapeMarkdownCell(result.unsupportedReason || "");
    const notes = [];
    for (const asset of result.suite.worker.assets || []) {
        if (asset.status === "unsupported") {
            notes.push(`${asset.id}: ${asset.unsupportedReason || "unsupported"}`);
        }
        if (asset.status === "failed") {
            notes.push(`${asset.id}: ${asset.message || "failed"}`);
        }
    }
    return escapeMarkdownCell(notes.join("; "));
}

function collectUnsupportedWorkerFixtures(results) {
    const map = new Map();
    for (const result of results) {
        for (const asset of result.suite?.worker.assets || []) {
            if (asset.status !== "unsupported") continue;
            const key = `${asset.id}:${asset.unsupportedReason || ""}`;
            const existing = map.get(key) || {
                assetId: asset.id,
                reason: asset.unsupportedReason || "Unsupported.",
                count: 0,
            };
            existing.count += 1;
            map.set(key, existing);
        }
    }
    return [...map.values()];
}

function countUnsupportedWorkerFixtures(results) {
    let count = 0;
    for (const result of results) {
        for (const asset of result.suite?.worker.assets || []) {
            if (asset.status === "unsupported") count += 1;
        }
    }
    return count;
}

function escapeMarkdownCell(value) {
    return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function groupByVersion(results) {
    const map = new Map();
    for (const result of results) {
        if (!map.has(result.version)) map.set(result.version, []);
        map.get(result.version).push(result);
    }
    return map;
}
